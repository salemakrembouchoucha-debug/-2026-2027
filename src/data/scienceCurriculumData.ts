export function getSubTopicIdForQuestion(q: QuestionItem): string {
  if (q.unitId === 1) {
    if (q.section === 'essay') return 'u1-essay';
    if (q.originalNumber <= 10) return 'u1-states';
    if (q.originalNumber <= 18) return 'u1-density';
    return 'u1-diffusion';
  } else {
    if (q.section === 'mcq') {
      if (q.originalNumber <= 6) return 'u2-microscope';
      if (q.originalNumber <= 15) return 'u2-cells';
      if (q.originalNumber <= 20) return 'u2-osmosis';
      return 'u2-specialized';
    }
    // Unit 2 essay
    if (q.originalNumber === 1) return 'u2-microscope';
    if (q.originalNumber === 2 || q.originalNumber === 3 || q.originalNumber === 5 || q.originalNumber === 8) {
      return 'u2-cells';
    }
    if (q.originalNumber === 4 || q.originalNumber === 7) return 'u2-osmosis';
    return 'u2-specialized';
  }
}

export function isQuestionAnswered(rec?: UserAnswerRecord): boolean {
  if (!rec) return false;
  if (rec.selectedOption) return true;
  if (rec.essayAnswers) {
    const values = Object.values(rec.essayAnswers);
    if (values.some((txt) => typeof txt === 'string' && txt.trim().length > 0)) {
      return true;
    }
  }
  if (rec.tableAnswers && Object.keys(rec.tableAnswers).length > 0) {
    return true;
  }
  if (rec.dragDropAnswers && Object.keys(rec.dragDropAnswers).length > 0) {
    return true;
  }
  if (rec.isSelfEvaluatedCorrect !== undefined) {
    return true;
  }
  return false;
}

